"""Frozen shared state for the bake-off.

Do not edit this file for one person's experiment. Everything here is either a
path convention or a number that has to be identical across every run for the
result files to be comparable. If you need a different value, pass it as an
argument to the run function instead.
"""
from __future__ import annotations

import os
from pathlib import Path

# ml/swiftbench/config.py -> ml/swiftbench -> ml -> repo root.
#
# `SWIFT_REPO_ROOT` overrides it. That exists for one reason: on Kaggle the package is imported
# from `/kaggle/input/<dataset>/ml/swiftbench`, where walking up two parents lands on
# `/kaggle/input` and every data path below would silently resolve to a directory that does not
# exist. See `ml/kaggle/README.md`.
REPO_ROOT = Path(os.environ.get("SWIFT_REPO_ROOT") or Path(__file__).resolve().parents[2])

DATASETS_DIR = REPO_ROOT / "datasets"
SPLITS_DIR = REPO_ROOT / "ml" / "splits"
REPORTS_DIR = REPO_ROOT / "ml" / "reports"
MODELS_DIR = REPO_ROOT / "ml" / "models"
PREDICTIONS_DIR = REPO_ROOT / "ml" / "predictions"

SPLIT_MANIFEST = SPLITS_DIR / "split_manifest.json"

LANGUAGES = ["english", "sinhala", "singlish", "tamil", "tamilish"]

# The one schema every datasets/<lang>/{train,test}_labeled.csv shares.
SCHEMA = ["id", "text_en", "text", "category", "sentiment", "priority"]

# `category` holds BANKING77's 77-way intent label. The rename to `intent` was
# attempted locally in July 2026 but never reached any commit, so the on-disk
# column is still `category`. TASK_LABEL_COLUMN is the only place that mapping
# lives -- if the CSVs are ever renamed, change it here and nowhere else.
TASK_LABEL_COLUMN = {
    "intent": "category",
    "sentiment": "sentiment",
    "priority": "priority",
}

TEXT_COLUMN = "text"

# Fixed label orders so confusion matrices and per-class tables line up across
# runs regardless of which classes a particular arm happened to predict.
SENTIMENT_LABELS = ["Neutral", "Negative"]
PRIORITY_LABELS = ["Low", "Medium", "High"]

# Sentiment is deliberately binary. `Negative` is the minority, the class that
# actually matters for escalation, and the only one worth scoring on.
SENTIMENT_POSITIVE_CLASS = "Negative"

RANDOM_STATE = 42

# Dev is carved out of the official BANKING77 train file; the official test file
# is never touched during model selection. 8,500 / 1,498 / 3,079 -- an absolute
# dev size rather than a fraction, so the split is reproducible to the row.
DEV_SIZE = 1498
